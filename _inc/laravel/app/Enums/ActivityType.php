	public static function normalize(string|int|null|self $value = null): ?self
	{
		if ($value instanceof self) {
			return $value;
		}

		if ($value === null) {
			return null;
		}

		$normalizedValue = preg_replace('/[^a-z0-9_]/', '', strtolower(trim((string) $value)));
		return self::tryFrom($normalizedValue);
	}

	public static function allCombinations(): array
	{
		$out = [];
		foreach (self::cases() as $case)
			$out[$case->value] = $case->value;
		return $out;
	}

	public function getAction(): string
	{
		$parts = explode('_', $this->value, 2);
		return $parts[0];
	}

	public function getEntity(): string
	{
		$parts = explode('_', $this->value, 2);
		return $parts[1] ?? '';
	}

	public function isDestructive(): bool
	{
		return $this === self::Delete || $this === self::Move;
	}

	public function isConstructive(): bool
	{
		return in_array($this, [self::Add, self::Create, self::Upload]);
	}

	public function getIcon(): string
	{
		$action = $this->getAction();

		return match ($action) {
