        $timeBefore = microtime(true);
        
        try {
            for ($i = 0; $i < 3; $i++) {
                $ctrl->index($this->makeRequest());
            }
        } catch (\Throwable $e) {
            // Method may throw, that's OK for perf test
        }
        
        $timeAfter = microtime(true);
        $memAfter = memory_get_usage(true);
        
        $execTime = ($timeAfter - $timeBefore) * 1000; // ms
