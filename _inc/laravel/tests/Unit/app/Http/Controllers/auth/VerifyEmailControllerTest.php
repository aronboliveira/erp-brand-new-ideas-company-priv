    /**
     * @group performance
     */
    public function test___invoke_performance_7(): void
    {
        $this->loginMockUser();
        $ctrl = new VerifyEmailController();
        
        $memBefore = memory_get_usage(true);
        $timeBefore = microtime(true);
        
        try {
            for ($i = 0; $i < 3; $i++) {
                $ctrl->__invoke($this->makeRequest(), 1);
            }
        } catch (\Throwable $e) {
            // Method may throw, that's OK for perf test
        }
        
        $timeAfter = microtime(true);
        $memAfter = memory_get_usage(true);
        
        $execTime = ($timeAfter - $timeBefore) * 1000; // ms
        $memUsed = ($memAfter - $memBefore) / 1024 / 1024; // MB
        
        // Assert reasonable performance bounds
        $this->assertLessThan(5000, $execTime, "__invoke took > 5s for 3 iterations");
        $this->assertLessThan(50, $memUsed, "__invoke used > 50MB for 3 iterations");
    }

