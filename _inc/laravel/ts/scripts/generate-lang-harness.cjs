#!/usr/bin/env node
"use strict";

/**
 * generate-lang-harness.cjs — Generate harness pages, Playwright specs,
 * and Jest unit tests for the 208 newly migrated lang TS routes.
 *
 * Usage:
 *   node scripts/generate-lang-harness.cjs [--dry-run]
 *
 * Outputs:
 *   tests/harness/pages/<slug>.html          (mock HTML pages)
 *   tests/harness-specs/<slug>.spec.ts       (Playwright E2E specs)
 *   tests/unit/<slug>.test.ts                (Jest unit tests)
 */

const fs = require("fs");
const path = require("path");

const DRY_RUN = process.argv.includes("--dry-run");
const TS_ROOT = path.resolve(__dirname, "..");
const ROUTES_DIR = path.join(TS_ROOT, "src", "public", "assets", "js", "routes");
const HARNESS_DIR = path.join(TS_ROOT, "tests", "harness", "pages");
const SPECS_DIR = path.join(TS_ROOT, "tests", "harness-specs");
const UNIT_DIR = path.join(TS_ROOT, "tests", "unit");

/* ---------- Discovery --------------------------------------------------- */

function collectLangRoutes(dir) {
  const results = [];
  if (!fs.existsSync(dir)) return results;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...collectLangRoutes(full));
    } else if (entry.name.endsWith(".ts") && full.includes("/lang/")) {
      results.push(full);
    }
  }
  return results;
}

/* ---------- Slug generation --------------------------------------------- */

/**
 * Convert route path to a slug:
 *   src/.../routes/invoices/lang/view.ts → invoices-lang-view
 */
function routeToSlug(routePath) {
  const rel = path.relative(ROUTES_DIR, routePath);
  return rel
    .replace(/\.ts$/, "")
    .replace(/[/\\]/g, "-")
    .replace(/[^a-zA-Z0-9_-]/g, "-")
    .replace(/-+/g, "-")
    .toLowerCase();
}

/**
 * Convert route path to the dist JS reference:
 *   invoices/lang/view.ts → /dist/public/assets/js/routes/invoices/lang/view.js
 */
function routeToDistPath(routePath) {
  const rel = path.relative(ROUTES_DIR, routePath).replace(/\.ts$/, ".js");
  return `/dist/public/assets/js/routes/${rel}`;
}

/**
 * Human-readable title from slug:
 *   invoices-lang-view → Invoices Lang View
 */
function slugToTitle(slug) {
  return slug
    .split("-")
    .map(w => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ");
}

/* ---------- Templates --------------------------------------------------- */

function htmlTemplate(slug, title, distPath) {
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <meta name="csrf-token" content="test-csrf-token">
  <title>${title} - Test Harness</title>
  <link href="https://cdn.jsdelivr.net/npm/bootstrap@5.3.3/dist/css/bootstrap.min.css"
        rel="stylesheet" crossorigin="anonymous">
</head>
<body>
  <div id="app" class="container mt-4">
    <h1 data-testid="page-title">${title}</h1>
    <div id="content" data-testid="content">
      <p>Harness page for <code>${slug}</code> (lang/i18n route).</p>
      <div id="toast-container" class="toast-container position-fixed bottom-0 end-0 p-3"></div>
    </div>
  </div>

  <!-- Mock globals -->
  <script>
    window.translations = {};
    window.__TEST_CSRF__ = "test-csrf-token";
    window.__TEST_APP_URL__ = "http://localhost:3333";
  </script>

  <!-- Bootstrap JS -->
  <script src="https://cdn.jsdelivr.net/npm/bootstrap@5.3.3/dist/js/bootstrap.bundle.min.js"
          crossorigin="anonymous"></script>

  <!-- Route script under test -->
  <script type="module" src="${distPath}"></script>
</body>
</html>
`;
}

function playwrightTemplate(slug, title) {
  return `/**
 * Playwright E2E spec for ${title} (lang route).
 * Auto-generated by generate-lang-harness.cjs
 */

import { test, expect } from "@playwright/test";

const PAGE = "http://localhost:3333/harness/pages/${slug}.html";

test.describe("${title}", () => {
  test.beforeEach(async ({ page }) => {
    await page.goto(PAGE);
  });

  test("page loads without console errors", async ({ page }) => {
    const errors: string[] = [];
    page.on("console", (msg) => {
      if (msg.type() === "error") errors.push(msg.text());
    });
    await page.waitForLoadState("networkidle");
    expect(errors).toHaveLength(0);
  });

  test("has correct title", async ({ page }) => {
    const heading = page.locator('[data-testid="page-title"]');
    await expect(heading).toBeVisible();
    await expect(heading).toContainText("${title.replace(/"/g, '\\"')}");
  });

  test("translations object exists on window", async ({ page }) => {
    const translations = await page.evaluate(() => (window as unknown as Record<string, unknown>).translations);
    expect(translations).toBeDefined();
    expect(typeof translations).toBe("object");
  });
});
`;
}

function jestTemplate(slug, distRelPath) {
  return `/**
 * Jest unit test for ${slug} (lang route).
 * Auto-generated by generate-lang-harness.cjs
 *
 * @jest-environment jsdom
 */

describe("${slug}", () => {
  beforeEach(() => {
    document.body.innerHTML = \`
      <div id="app">
        <div id="content"></div>
        <div id="toast-container"></div>
      </div>
    \`;
    (window as unknown as Record<string, unknown>).translations = {};
  });

  test("module can be imported without throwing", async () => {
    await expect(import("../${distRelPath}")).resolves.toBeDefined();
  });

  test("window.translations is populated after import", async () => {
    await import("../${distRelPath}");
    const t = (window as unknown as Record<string, unknown>).translations;
    expect(t).toBeDefined();
    expect(typeof t).toBe("object");
  });
});
`;
}

/* ---------- Main -------------------------------------------------------- */

function main() {
  const langRoutes = collectLangRoutes(ROUTES_DIR);
  console.log(`Found ${langRoutes.length} lang route files`);
  if (DRY_RUN) console.log("** DRY RUN **");

  let htmlCount = 0;
  let specCount = 0;
  let unitCount = 0;

  for (const route of langRoutes) {
    const slug = routeToSlug(route);
    const title = slugToTitle(slug);
    const distPath = routeToDistPath(route);

    // Harness HTML page
    const htmlPath = path.join(HARNESS_DIR, `${slug}.html`);
    if (!fs.existsSync(htmlPath)) {
      if (!DRY_RUN) {
        fs.mkdirSync(path.dirname(htmlPath), { recursive: true });
        fs.writeFileSync(htmlPath, htmlTemplate(slug, title, distPath));
      }
      htmlCount++;
    }

    // Playwright spec
    const specPath = path.join(SPECS_DIR, `${slug}.spec.ts`);
    if (!fs.existsSync(specPath)) {
      if (!DRY_RUN) {
        fs.mkdirSync(path.dirname(specPath), { recursive: true });
        fs.writeFileSync(specPath, playwrightTemplate(slug, title));
      }
      specCount++;
    }

    // Jest unit test
    const unitPath = path.join(UNIT_DIR, `${slug}.test.ts`);
    if (!fs.existsSync(unitPath)) {
      const distRelPath = `../${path
        .relative(TS_ROOT, route)
        .replace(/^src\//, "dist/")
        .replace(/\.ts$/, ".js")}`;
      if (!DRY_RUN) {
        fs.mkdirSync(path.dirname(unitPath), { recursive: true });
        fs.writeFileSync(unitPath, jestTemplate(slug, distRelPath));
      }
      unitCount++;
    }
  }

  console.log(`\nGenerated:`);
  console.log(`  Harness HTML pages: ${htmlCount}`);
  console.log(`  Playwright specs:   ${specCount}`);
  console.log(`  Jest unit tests:    ${unitCount}`);
  console.log(`  Total new files:    ${htmlCount + specCount + unitCount}`);
}

main();
