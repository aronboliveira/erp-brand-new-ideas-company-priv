	public static function filterByAction(string $action): array
	{
		return array_filter(
			self::allCombinations(),
			fn($combination) => str_starts_with($combination, $action)
		);
	}

	public static function filterByEntity(string $entity): array
	{
		return array_filter(
			self::allCombinations(),
			fn($combination) => str_ends_with($combination, '_' . $entity) ||
				($entity === '' && !str_contains($combination, '_', 1))
		);
	}

